# （3）例三（出现在Change2Corresp()函数中）：
# 构造一个示例表格：
df3 <- data.frame(
    A = c("1","","1+2+3")
)
# 先看直接通过mutate()函数中使用管道符的结构：
df3_numeric <- df3 %>% 
    mutate(
        A = if_else(
            str_detect(A,"\\+"),
            str_replace_all(A,".+\\+(.+)","\\1"),
            A
        ) %>% 
            {
                if_else(. == "",0,as.numeric(.))
            }
    )
# 由于管道符后面的ifelse()/if_else()函数中不存在用单独的占位符表示的参数，因此需要用大括号将其括起来。

# 如果将上述mutate()函数中的内容改写成在across()中使用的匿名函数的形式，会产生警报：
    # Warning message:
    # There was 1 warning in `mutate()`.
    # ℹ In argument: `across(...)`.
    # Caused by warning in `ifelse()`:
    #· ! NAs introduced by coercion 
df3_numeric_warning_1 <- df3 %>% 
    mutate(
        across(
            A,
            ~if_else(
                str_detect(.x,"\\+"),
                str_replace_all(.x,".+\\+(.+)","\\1"),
                .x
            ) %>% 
                {
                    if_else(. == "",0,as.numeric(.))
                }
        )
    )
# 结果变成：1、0、NA
## 这是因为如果在across()函数中使用管道符，across()函数创设的环境会阻碍管道符对右边函数中占位符的识别，此时“.”会被识别为across()环境中匿名函数的参数“.x”（当然也可以写成“.”），也就是across()函数的第一个参数对应的列内容，因此，“~”和管道符之间的部分实际不会发挥作用，上述命令实际上等同于：
df3_numeric_warning_2 <- df3 %>% 
    mutate(
        across(
            A,
            ~if_else(. == "",0,as.numeric(.))
        )
    )
## 而在之前只使用mutate()函数的结构中，管道符可以顺利将右边函数中的“.”识别为占位符，因此能够将左边的结果顺利输入右边函数。

## 而（四-2）的例子中虽然也在across()函数中使用了管道符，但由于在这个例子中没有出现占位符，因此可以正常运行。总而言之，应该尽量避免在across()函数中使用管道符。

# 如果想用across()函数中的匿名函数完成上述任务，可以将上述结构改写为：
df3_numeric_modified <- df3 %>% 
    mutate(
        across(
            A,
            ~{
                numeric_1 <- if_else(
                    str_detect(.x,"\\+"),
                    str_replace_all(.x,".+\\+(.+)","\\1"),
                    .x
                )
                numeric_2 <- if_else(
                    numeric_1 == "",
                    0,
                    as.numeric(numeric_1)
                )
                return(numeric_2)
            }
        )
    )
#* 原文中由于不涉及动态列名，因此使用了mutate()函数直接处理而没有选择across()函数中的匿名函数。

