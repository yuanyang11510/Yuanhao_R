## 总结：上述四个案例体现出的各种处理方法的适用情形可以表述为以下分类讨论的形式：
# -->> 在pivot_longer()函数的names_transform参数中处理新生成的列：
    # 只能使用匿名函数或者提前定义的函数处理（案例一）
# -->> 在mutate()函数中处理：
    # 可以直接在mutate()函数中处理，也可以在across()函数中用匿名函数处理（案例二三四）：

# 匿名函数后接管道符时：
# -->> 右边函数的参数中存在单独使用的占位符：
    # 在mutate()函数中，右边函数即使不用大括号{}括起来，也可以正常运行（案例一二）：
        # -->> 右边函数的第一个参数恰好是左边的结果：
            # 即使在across()函数中也可以正常运行（案例二）
        # -->> 右边函数的第一个参数不是左边的结果：
            # 如果在across()函数中使用该结构，会导致占位符被识别成across()函数的第一个参数代表的列内容，从而导致“~”和管道符之间的内容失效（案例未涉及）
# -->> 右边函数的参数中不存在单独使用的占位符：
    # 在mutate()函数中，右边函数需要用大括号括起来，如果在across()函数中使用该结构，会导致占位符被识别成across()函数的第一个参数代表的列内容，从而导致“~”和管道符之间的内容失效（案例三四）
## 实践中，应该尽量避免匿名函数后接管道符的结构，在mutate()函数中，推荐的做法有两种：如果不涉及动态列名，可以直接使用管道符连接的多步命令处理；如果涉及动态列名，推荐在across()函数中使用匿名函数处理，但不要用匿名函数后接管道符，而是将多步命令以代码块的形式放在一个匿名函数中，避免使用管道符。







