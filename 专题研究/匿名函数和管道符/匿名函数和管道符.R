    # ℹ In index: 1.
    # Caused by error in `if_else()`:
    #`` ! Can't combine `true` <double> and `false` <character>.
# 这种冲突下只可能将yes参数从数值型改为字符型，而yes参数的位置一旦改为数值型就会导致参数中不再存在独立的占位符，从而导致管道符右边的函数自动将左边的结果输入第一个参数，之前的参数位置顺次后移，导致报错。为了解决if_else()函数的这一问题，需要用大括号{}将管道符右边的内容括起来：
map(
    1:3,
    ~ (.x + 1) %>% 
        {
            if_else(
                . == 3,
                as.character(.),
                "!= 3"
            )
        }
)

