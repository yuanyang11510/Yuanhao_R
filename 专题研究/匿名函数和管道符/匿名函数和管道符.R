## 额外的注释：if_else()函数和if_else()函数的区别（二）

# 注意，如果想上述命令那样，yes参数和no参数的数据类型不一致，ifelse()函数会无形之中强行将其中一种数据类型转换为另一种相同的数据类型，比如上述命令中，ifelse()就将左边的结果中数值型的3强行转换为结果中字符型的"3"，而if_else()函数则直接要求yes/no参数的类型必须相同，否则会报错：
