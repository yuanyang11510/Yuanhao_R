# （一）匿名函数
# （1）最普通的函数
f <- function(x){
  x + 1
}
# f 是函数名。
# function(x){...} 是函数本体。

# 调用：
f(3) # 结果是4

# （2）匿名函数
# 匿名函数，也叫lambda函数，是临时定义的函数：只有函数本体，没有名字。
function(x){
  x + 1
}
# 它仍然是函数，只是没有赋值：f <- function(x){...}。

# （3）为什么需要匿名函数？
# 因为很多时候，这个函数只用一次。
lapply(
    1:3, 
    function(x){
        x + 1
    }
)
# 对每个 x：执行 x+1

# （4）R 4.1之后基础命令中的简写：\(x)
# R 4.1之后，基础命令中的匿名函数可以使用\(x)简写：
lapply(
    1:3,
    \(x) x+1
)

# （5）tidyverse包中的简写：~
# 在 tidyverse（确切地说是purrr包）里，经常写：
~ .x + 1
# 其实等价于：
function(.x){
  .x + 1
}
# 上面的lapply函数也可以写成：
map(
    1:3,
    ~ .x + 1 
)
# map()函数是lapply()函数的tidyverse版本。
# 但是lapply()函数中不能使用“~”简写，因为lapply()属于基础函数。

# （6）匿名函数的参数
# “.x”是purrr中预定义的匿名函数参数，在map2()函数中还预定义了“.y”参数：
map2(
    c(1,2),c(3,4),
    ~ .x + .y
) # 返回一个包含了4、6两个成员的列表

# “.x”也可以写成“.”，但不推荐，因为在管道符中也会用到“.”，容易混淆。

# 如果使用基础命令中的匿名函数写法，则可以自由定义函数参数：
lapply(
    1:3,
    function(a) a + 1
)
lapply(
    1:3,
    \(a) a + 1
)

# 上述三种形式：
    # function(x) x + 1
    # \(x) x + 1
    # ~ .x + 1
# 前两种使用class()会返回"function"，而第三种使用class()会返回"formula"，可以被tidyverse自动转成函数。

# （二）管道符（pipe）
# 管道符（%>%）是tidyverse包（确切地说是magrittr包）中的一个重要工具，能够让代码更简洁、更易读。

# （1）最核心思想：把f(g(x))改写成：x %>% g() %>% f()。

# （2）%>% 做了什么：把左边结果传给右边函数，默认左边的结果作为右边函数的第一个参数。
1:3 %>% sum()
# 等价于：
sum(1:3)

"x" %>% paste0("a")
# 等价于：
paste0("x", "a")

# （3）函数调用
# 上述sum()函数带有括号()，表示函数调用，如果没有括号而只有函数名，管道符会自动调用该函数，效果相同：
1:3 %>% sum
# 但是R 4.1之后加入的基础命令中的管道符（|>）不会在这种情况下自动调用函数：
1:3 |> sum() # 返回6
# "1:3 |> sum" # 会报错（该命令如果不加引号，即使注释掉，VS Code的静态检查也会将文件名标红）：
    # Error in sum : 
    #   The pipe operator requires a function call as RHS (<input>:1:8)

# （4）占位符（placeholder）
# 如果不想将左边的结果作为右边函数的第一个参数，可以写：
"x" %>% paste0("a", .)
# 等价于：
paste0("a", "x")

# 大多数情况下，也可以将右边函数的第一个参数以占位符的形式写出：
"x" %>% paste0("a")
"x" %>% paste0(., "a") # 效果和上一条命令相同

# 基础命令中的管道符（|>）不使用像magrittr包中那样的占位符机制，如果遇到类似的情况，需要使用匿名函数解决：
"x" |> paste0("a")
# "x" |> paste0("a",.) # 会报错
"x" |> (\(x) paste0("a",x))()
# 注意匿名函数本体外面的括号()是必须的，用来标示函数的整体表达式，后面跟的那个括号()也是必须的，用来调用函数，类似前文sum()函数中的括号()。
"x" |> {\(x) paste0("a",x)}()
# 大括号{}一般用来标示存在多条表达式的代码块，这是使用习惯的问题，此处匿名函数虽然只有一条表达式，但也可以用大括号来标示，因此效果相同。

# （三）“~”类匿名函数后接管道符
# （1）一个正常运行的例子
# 先看下面这个例子：
map(
    c("a","b","c"),
    ~ paste0(.x,"x") %>% paste0("y",.)
)
# 这里相当于做了两件事情：
    # （a）tmp <- paste0(c("a","b","c"),"x")
    #* 注意此时匿名函数的参数用“.x”表示（c("a","b","c")），也可以写成“.”。
    # （b）paste0("y", tmp)
    #* 注意此时管道符后的占位符用“.”表示（tmp），不能写成其他形式。

# （2）一个报错的例子
# 再看下面这个例子：
# map(
#     1:3,
#     ~ .x + 1 %>% 
#         ifelse(
#             . < 3,
#             "< 3",
#             ">= 3"
#         )
# )
# 会报错：
    # Error in `map()`:
    # ℹ In index: 1.
    # Caused by error in `ifelse()`:
    #· ! unused argument (">= 3")

## 这是因为如果像上面这样在占位符“.”后面再加上另一个运算命令“< 3”，“. < 3”整体就构成了一个新的参数，而函数的其它参数中又没有用到独立的占位符“.”（关于参数中用到了独立的占位符的情况的例子，见后文（四-1）），因此右边的函数会将“. < 3”这个新的参数作为第二个参数，而第一个参数依然是独立的占位符“.”代表的左边的结果。

# 上述命令相当于做了两件事情：
    # （a）tmp <- .x + 1
    #! （b）ifelse(tmp,tmp < 3, "< 3", ">= 3")
    #* 由于ifelse()函数最多只能接受三个参数，因此会报错。

## 如果想要阻止这种机制，可以将管道符右边的内容用大括号{}括起来，形成一个代码块，具体的例子见后文（三-4）。

# （3）管道符和算术运算符的优先级（两者都属于二元运算符binary operator）
# 在研究上述这类例子的过程中，还发现了另一个重要的问题：管道符（%>%）的优先级高于算术运算符（+），因此像“~ .x + 1 %>% ...”的结构会先运算“1 %>% ...”（结果记为tmp），再运算“.x + tmp”。
# 看下面这两个例子：
map(
    1:3,
    ~ .x + 1 %>% 
        ifelse(
            . < 3,
            "< 3"
            # ">= 3"
        )
) # 返回一个包含2、3、4的列表
map(
    1:3,
    ~ .x + 1 %>% 
        ifelse(
            . < 3
            # "< 3"
            # ">= 3"
        )
) # 结果和上一条命令相同

# 上面两条命令实际做了两件事情：
    # （a）tmp <- ifelse(1,1 < 3,"< 3")，或者
        # tmp <- ifelse(1,1 < 3)
    #* 由于test参数为1，恒为真，因此始终返回yes参数的值，即1 < 3的结果，即TRUE。
    #* 这里涉及一个ifelse()函数的特点：如果test的结果恒为真，ifelse()可以接受最后一个参数no空缺，所以第二种情况也可以正常运行。
    # （b）1:3 + tmp（TRUE）
    #* 由于数值运算中TRUE被当作1处理，因此结果是2、3、4。

# 如果想要优先计算“.x + 1”，可以在“.x + 1”外面加上括号（小括号、大括号都可以，但一般习惯用小括号），改变运算顺序：
map(
    1:3,
    ~ (.x + 1) %>% 
        ifelse(
            . < 3,
            "< 3" # 也可以注释掉，不再演示
            # ">= 3"
        )
) # 返回一个包含TRUE、FALSE、FALSE的列表

# 上面这条命令实际做了两件事情：
    # （a）tmp <- 1:3 + 1
    #* 结果得到2:4
    # （b）ifelse(tmp, tmp < 3, "< 3")
    #* test参数为tmp（2:4），恒为真，因此始终返回yes参数的值，即2:4 < 3的结果，即TRUE、FALSE、FALSE
    #* 此处还涉及ifelse()函数的yes/no参数为向量时的处理：如果test参数的长度比yes/no参数的长度短，则以test参数的长度为准进行取值，比如下面这条命令会返回"A"、"F"、"C"，分别来自yes参数的第一项、no参数的第二项、yes参数的第三项。
ifelse(c(T,F,T),c("A","B","C","D"),c("E","F","G","H"))
    #* 如果yes/no的向量长度比test参数的向量长度短，会遵循“向量回收机制”（vector recycling），自动将长度较短的向量根据之前的内容循环补全，然后进行取值。比如下面这个命令会返回"A"、"B"、"C"、["A"]、"D"、"E"、["D"]，第四个位置的"A"和最后一个位置的"D"是根据yes/no参数之前的内容补全的。
ifelse(c(T,T,T,T,F,F,F),c("A","B","C"),c("D","E"))

# 但是下面这个例子：
# map(
#     1:3,
#     ~ .x + 1 %>% 
#         ifelse(
#             .,
#             "< 3",
#             ">= 3"
#         )
# )
# 会报错：
    # Error in `map()`:
    # ℹ In index: 1.
    # Caused by error in `.x + 1 %>% ifelse(., "< 3", ">= 3")`:
    #· ! non-numeric argument to binary operator

# 上面这条命令实际做了两件事情：
    # （a）tmp <- ifelse(1, "< 3", ">= 3")，由于test参数为1，恒为真，因此始终返回yes参数的值，即"< 3"。
    #! （b）1:3 + tmp（"< 3"）
    #* 由于数值运算中字符串不能被当作数值处理，因此会报错。

