# （4）如何正确地实现（2）（3）中原本想要实现的目的
# 上述（2）中的命令会报错，（3）中的一些命令虽然不会报错，但是结果并非一开始的本意：
    # （a）先计算“.x + 1”，得到一个数值向量。
    # （b）再将这个数值向量传给ifelse()/if_else()函数的test参数，根据逻辑值判断式得到相应的逻辑值。

# 为了实现一开始的目的，存在三种解决办法：
# （A）一种做法是先将map()函数搭配匿名函数得到的结果赋值给一个变量，再将该变量输入ifelse()/if_else()函数：
lst <- map(
    1:3,
    ~ .x + 1
) # 返回一个包含了2、3、4三个成员的列表
if_else(
    lst < 3,
    "< 3",
    ">= 3"
) # 返回一个包含"< 3" 、">= 3"、">= 3"的向量（ifelse()/if_else()函数始终返回向量）
#* 但是这种做法需要在全局环境中赋值，不够优美。

# （B）第二种做法是将管道符后面的内容用大括号{}括起来，形成一个代码块，在管道符右边的函数参数中没有出现单独的占位符的情况下，代码块可以组织管道符自动将左边的结果输入右边函数的第一个参数，此时代码块中的函数参数位置和实际输入的位置一致：
map(
    1:3,
    ~ (.x + 1) %>% # 不要忘记在“.x + 1”外面加上括号，改变运算顺序
        {
            if_else(
                . < 3,
                "< 3",
                ">= 3"
            )
        }
)
# 上述代码块的效果相当于先执行了一步赋值操作，可以写成伪代码：
# map(
#     1:3,
#     ~ (.x + 1) %>% 
#         {
#             . <- lhs <<<--
#             if_else(
#                 . < 3,
#                 "< 3",
#                 ">= 3"
#             )
#         }
# )
#* 但是这种做法依然可能需要面对管道符和算术运算符的优先级问题，比如上面这条命令，大括号{}容易让人误以为代码块中的内容会在管道符左边的结果得出之后执行，但其实仍然需要将管道符左边的内容用括号括起来。

# （C）第三种做法是将第一种做法中的两步合并到一个匿名函数中，这时匿名函数的内容是多个表达式构成的代码块，用大括号{}标示出来：
map(
    1:3,
    ~{
        x <- .x + 1
        result <- if_else(
            x < 3,
            "< 3",
            ">= 3"
        )
        return(result)
    }
) # 返回一个包含了"< 3"、">= 3"、">= 3"三个成员的列表
#* 这种做法中赋值只在匿名函数的局部环境中进行，不会影响到全局环境中的变量，而且由于不再使用管道符，不会存在管道符合算术运算符的优先级问题，因此更加推荐。

## 上述（1）（2）（3）（4）的讨论提醒我们，要谨慎使用“~”类匿名函数后接管道符，使用时要注意两点：
    # （a）管道符后面的占位符如果搭配其他运算符使用，就会组成一个新的参数，如果没有在其他参数中使用独立的占位符，并且没有将管道符右边的内容用大括号{}括起来，右边的函数会将这一新的参数作为第二个参数，第一个参数依然是独立的占位符代表的左边的结果。
    # （b）管道符的优先级高于算术运算符，如果左边的表达式里存在算术运算符，且左边的表达式没有用括号括起来，那末算术运算符右边的变量会优先和管道符及其之后的内容结合，得到的结果再和算术运算符结合进行计算。
## 更好的做法是将多个步骤以代码块的形式放在一个匿名函数中，避免同时使用管道符。

# （四）下面举几个以前在构造函数时使用匿名函数后接管道符的例子
# （1）例一（出现在Origin()函数中）：
# 构造一个示例表格：
df1 <- data.frame(
    Proto = c("*A","*B","*C"),
    L1 = c("a1_1|a1_2","b1","c1"),
    L2 = c("a2","b2_1|b2_2","c2"),
    L3 = c("a3","b3","c3_1|c3_2")
)

# 在names_transform参数中使用匿名函数后接管道符：
df1_longer <- df1 %>% separate_wider_delim(
    col = where(~any(grepl("\\|",.))),
    delim = "|",
    names_sep = "_",
    too_few = "align_start"
) %>% 
    pivot_longer(
        cols = everything(),
        values_to = "Initial",
        values_drop_na = TRUE,
        names_to = "Origin",
        names_transform = list(
            Origin = ~str_remove_all(.x, "_\\d+") %>% 
                if_else(
                    . == "Proto",
                    .,
                    paste0(.," < ","Proto")
                )
        )
    )
## 上述匿名函数后接管道符的结构之所以可以正常运行，是因为管道符之后的if_else()函数的参数中使用了独立的“.”，因此“. == 'Proto'”这个参数虽然会被识别成一个新的参数，但是确实会被放置在第一个参数的位置，而第二个位置则是独立的占位符代表的左边的结果。

# 为了避免同时使用管道符，可以将上述结构改写为：
df1_longer_modified <- df1 %>% separate_wider_delim(
    col = where(~any(grepl("\\|",.))),
    delim = "|",
    names_sep = "_",
    too_few = "align_start"
) %>% 
    pivot_longer(
        cols = everything(),
        values_to = "Initial",
        values_drop_na = TRUE,
        names_to = "Origin",
        names_transform = list(
            Origin = ~{
                origin_1 <- str_remove_all(.x, "_\\d+")
                origin_2 <- if_else(
                    origin_1 == "Proto",
                    origin_1,
                    paste0(origin_1," < ","Proto")
                )
                return(origin_2)
            }
