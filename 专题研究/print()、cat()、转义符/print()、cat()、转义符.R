# 以下部分原理的解释参考了ChatGPT。

# print()会返回底层形式，cat()则返回经过“字符串解析”之后的表层形式。

# 这个区别在涉及转义符"\"的时候会体现出来，下面给出几个涉及转义符"\"的字符串，分别用print()函数和cat()函数输出。
#* cat()函数输出的内容的最后一行在VS Code的控制台中无法显示，因此此处在最后加了一个换行符"\n"，下同。

# 例一：响铃符号"\a"
print("\a") # 输出"\a"
cat("\a\n") # 输出
# "\a"这个字符串中，"\"是转义符，"\a"表示响铃字符。print("\a")输出底层形式"\a"，而cat("\a")会对该字符串进行解析之后输出表层形式。
# cat("\a")在R Studio的控制台中会输出一个类似“·”的符号，在VS Code的控制台中无法显示出来。

# 例二：双引号"\""
print("\"") # 输出"\""
cat("\"\n") # 输出"
# R的字符串中的双引号"""需要使用转义符"\""。print("\"")输出底层形式"\"", 而cat("\"")输出表层形式"""。

# 例三：反斜杠"\\"
print("\\") # 输出"\\"
cat("\\\n") # 输出\
# R的字符串中的反斜杠"\"需要使用转义符"\"。print("\\")输出底层形式"\\", 而cat("\\")输出表层形式"\"。

## 例四："\\a"
print("\\a") # 输出"\\a"
cat("\\a\n") # 输出\a
# "\\a"需要分析为两部分，"\\"相当于例三中的反斜杠，"a"就是普通的字符串。print("\\a")输出底层形式"\\a"，而cat("\\a")输出表层形式"\a"。

